from datetime import date
from typing import Protocol

from stash.capture.message import IncomingMessage
from stash.capture.results import Deferred, Filed, ProcessResult
from stash.domain import CaptureStatus, Filing, Item, Outcome, RawCapture, Step
from stash.enrich.links import LinkInfo
from stash.lifecycle.results import Completion, ItemHistory


class IntakeStore(Protocol):
    def add_capture(self, capture: RawCapture) -> bool: ...

    def set_capture_status(self, capture_id: str, status: CaptureStatus) -> None: ...

    def pending_captures(self) -> list[RawCapture]: ...

    def get_item(self, item_id: str) -> Item | None: ...

    def save_item(self, item: Item) -> None: ...


class FixStore(Protocol):
    def get_item(self, item_id: str) -> Item | None: ...

    def update_item(self, item: Item, *, replacing: Item) -> None: ...

    def delete_item_if_untouched(self, item_id: str) -> bool: ...

    def get_capture(self, capture_id: str) -> RawCapture | None: ...

    def set_capture_status(self, capture_id: str, status: CaptureStatus) -> None: ...


class LifecycleActions(Protocol):
    def complete(self, item_id: str, *, on: date | None = None) -> Completion: ...

    def rate(self, outcome_id: str, rating: int) -> Outcome: ...

    def keep(self, item_id: str, kept: bool) -> Item: ...

    def didnt_happen(self, item_id: str, on: date) -> Item: ...

    def history(self, item_id: str) -> ItemHistory: ...


class PlanningActions(Protocol):
    def confirm_all(self, item_id: str) -> tuple[Step, ...]: ...

    def discard(self, item_id: str) -> None: ...

    def complete_step(self, step_id: str) -> Step: ...


class ItemLookup(Protocol):
    def get_item(self, item_id: str) -> Item | None: ...


class ItemLinker(Protocol):
    def link(self, item: Item) -> None: ...


class CaptureFiler(Protocol):
    def file(self, text: str, link: LinkInfo | None) -> Filing: ...


class CaptureIntake(Protocol):
    def receive(self, message: IncomingMessage) -> RawCapture | None: ...

    def process(self, capture: RawCapture) -> ProcessResult: ...

    def process_agent(self, capture: RawCapture) -> Filed | Deferred: ...

    def handle(self, message: IncomingMessage) -> ProcessResult: ...

    def retry_pending(self) -> list[ProcessResult]: ...


class AgentIntake(Protocol):
    def receive(self, message: IncomingMessage) -> RawCapture | None: ...

    def process_agent(self, capture: RawCapture) -> Filed | Deferred: ...
